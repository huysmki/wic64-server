    lda #$1b
    sta $d011
    lda #$c8
    sta $d016
    lda #$17                            ; upper/lowercase character set
    sta $d018
    lda $dd00
    ora #%00000011                      ; VIC bank 0
    sta $dd00
    lda #$00
    sta $d020
    sta $d021
    lda #$80                            ; disable shift+C= charset switching
    sta $0291
    ; fall through

apply_colors:
    ldx #0
    lda #15                             ; light grey
-   sta color_ram,x
    sta color_ram+$100,x
    sta color_ram+$200,x
    sta color_ram+$2e8,x
    inx
    bne -

    ldx #39
-   lda #3                              ; title: cyan
    sta color_ram,x
    lda #1                              ; status line: white
    sta color_ram + 24*40,x
    lda #12                             ; help: grey
    sta color_ram + 22*40,x
    sta color_ram + 23*40,x
    dex
    bpl -

    lda #<(color_ram + 2*40 + 1)        ; entry letters: yellow (rows 2-21, column 1)
    sta letter_color+1
    lda #>(color_ram + 2*40 + 1)
    sta letter_color+2
    ldx #20
-   lda #7
letter_color:
    sta $ffff
    lda letter_color+1
    clc
    adc #40
    sta letter_color+1
    bcc +
    inc letter_color+2
+   dex
    bne -
    rts

clear_screen:
    ldx #0
    lda #' '
-   sta screen,x
    sta screen+$100,x
    sta screen+$200,x
    sta screen+$2e8,x
    inx
    bne -
    rts

; Shows the screen code string at A/Y (terminated by $ff) in the status line, padded with spaces
show_status:
