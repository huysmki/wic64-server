    sty status_source+2
    ldx #0
status_source:
-   lda $ffff,x
    cmp #$ff
    beq +
    sta status_row,x
    inx
    cpx #40
    bne -
    rts
+   lda #' '
-   sta status_row,x
    inx
    cpx #40
    bne -
    rts

show_now_playing:
    ldx #39
-   lda #' '
    ldy playing
    beq +
    lda now_playing,x
+   sta status_row,x
    lda #1
    sta color_ram + 24*40,x
    dex
    bpl -
    lda #$ff                            ; redraw the time
    sta shown_seconds
    rts

