startup_start:
main:
    lda #$37
    sta $01
    jsr restore_ui
    jsr clear_screen

    +status msg_detecting
    +wic64_detect
    bcc +
    +status msg_no_device
    rts
+   beq +
    +status msg_legacy_firmware
    rts

+   jsr ask_server_address
    jsr save_address

    ; keep a copy of this startup code for F2 (change the server address)
    lda #<startup_start
    sta copy_source
    lda #>startup_start
    sta copy_source+1
    lda #<startup_stash
    sta copy_target
    lda #>startup_stash
    sta copy_target+1
    jsr copy_pages

    +wic64_set_timeout TIMEOUT
    +wic64_dont_disable_irqs            ; keep the music playing during transfers

    ; Timeouts and errors jump to these handlers with the stack reset to this level
    tsx
    stx main_stack
    +wic64_set_timeout_handler on_timeout
    +wic64_set_error_handler on_wic64_error

    lda #SECTION_PROGRAMS
    jmp open_section

;------------------------------------------------------------------------------
; Startup screen: edit the proposed server address, RETURN accepts it
;------------------------------------------------------------------------------

ask_server_address:
    lda #0                              ; F2 later: a failing request here must not jump to the menu
    sta wic64_handlers_suspended
    jsr clear_screen
    lda #<msg_title
    ldy #>msg_title
    ldx #0
    jsr print_row
    lda #<msg_enter_address
    ldy #>msg_enter_address
    ldx #3
    jsr print_row
    lda #<msg_address_help
    ldy #>msg_address_help
    ldx #8
    jsr print_row
    +status msg_empty

    ; propose the address that worked last time, if it is on the disk
    jsr load_saved_address
    lda address_loaded
    beq +
    +status msg_address_loaded
+
    ; show the C64's own address, handy to check both are on the same network
    +wic64_execute ip_request, c64_ip
    bcs edit_address
    bne edit_address
    lda #<msg_this_c64
    ldy #>msg_this_c64
    ldx #11
    jsr print_row
    ldx #0
-   lda c64_ip,x
    beq edit_address
    sta screen + 11*40 + 10,x           ; digits and dots are the same in ASCII and screen codes
    inx
    cpx #15
    bne -

edit_address:
    ldx #ADDRESS_MAX
    lda #1                              ; white input field
-   sta color_ram + ADDRESS_ROW*40 + 2,x
    dex
    bpl -

edit_address_loop:
    jsr draw_address
-   jsr GETIN
    beq -

    cmp #KEY_RETURN
    bne +
    lda address_length
    beq edit_address_loop
    lda #1                              ; the timeout and error handlers work again
    sta wic64_handlers_suspended
    rts

+   cmp #KEY_DEL
    bne +
    lda address_length
    beq edit_address_loop
    dec address_length
    inc address_changed
    jmp edit_address_loop

    ; accept 0-9 . : - and letters (for host names)
+   ldx address_length
    cpx #ADDRESS_MAX
    bcs edit_address_loop
    cmp #'-'
    beq add_address_char
    cmp #'.'
    beq add_address_char
    cmp #'0'
    bcc edit_address_loop
    cmp #':'+1
    bcc add_address_char
    cmp #KEY_A
    bcc edit_address_loop
    cmp #KEY_A+26
    bcs edit_address_loop
    ora #$20                            ; PETSCII letter -> ASCII lowercase
add_address_char:
    sta server_address,x
    inc address_length
    inc address_changed
    jmp edit_address_loop

; Shows the address (ASCII) as screen codes with a reverse space as cursor
draw_address:
    ldx #0
draw_address_char:
    cpx address_length
    bcs draw_address_cursor
    lda server_address,x
    cmp #$60
    bcc +
    sbc #$60                            ; ASCII lowercase -> screen code
+   jmp draw_address_store
draw_address_cursor:
    lda #' '
    cpx address_length
    bne draw_address_store              ; past the cursor: space
    lda #$a0                            ; cursor: reverse space
draw_address_store:
    sta screen + ADDRESS_ROW*40 + 2,x
    inx
    cpx #ADDRESS_MAX+1
    bne draw_address_char
    rts

;------------------------------------------------------------------------------
; The address is remembered in the SEQ file "WIC64 SERVER" on device 8.
; Without a drive or disk nothing happens: the built-in address is proposed.
;------------------------------------------------------------------------------

address_file    = 2                     ; logical file number
saved_address   = $0340                 ; tape buffer, free while the browser starts

load_saved_address:
    lda #0
    sta $9d                             ; no KERNAL messages
    sta file_index
    lda #read_name_end - read_name
    ldx #<read_name
    ldy #>read_name
    jsr open_address_file
    bcs close_address_file
    ldx #address_file
    jsr CHKIN
    bcs close_address_file

-   jsr CHRIN
    cmp #KEY_RETURN                     ; end of the line (also what a missing file gives)
    beq ++
    jsr is_address_char
    bcs close_address_file              ; not an address: ignore the file
    ldx file_index
    sta saved_address,x
    inc file_index
    lda $90                             ; end of file or error
    bne ++
    cpx #ADDRESS_MAX-1
    bcc -

++  ldx file_index
    beq close_address_file
    stx address_length
-   dex
    lda saved_address,x
    sta server_address,x
    txa
    bne -
    inc address_loaded

close_address_file:
    jsr CLRCHN
    lda #address_file
    jmp CLOSE

; Saves the address when it was changed or was not on the disk yet
save_address:
    lda address_loaded
    beq +
    lda address_changed
    beq ++
+   +status msg_saving_address
    lda #0
    sta $9d
    sta file_index

    ; delete the old file ("S:WIC64 SERVER" on the command channel)
    lda #scratch_name_end - scratch_name
    ldx #<scratch_name
    ldy #>scratch_name
    jsr SETNAM
    lda #15
    ldx #8
    ldy #15
    jsr SETLFS
    jsr OPEN
    php
    lda #15
    jsr CLOSE
    plp
    bcs ++                              ; no drive

    lda #write_name_end - write_name
    ldx #<write_name
    ldy #>write_name
    jsr open_address_file
    bcs close_address_file
    ldx #address_file
    jsr CHKOUT
    bcs close_address_file
-   ldx file_index
    lda server_address,x
    jsr CHROUT
    inc file_index
    lda file_index
    cmp address_length
    bne -
    lda #KEY_RETURN
    jsr CHROUT
    jmp close_address_file
++  rts

; A/X/Y: file name for SETNAM. Opens it as logical file 2 on device 8, carry set on error.
open_address_file:
    jsr SETNAM
    lda #address_file
    ldx #8
    ldy #address_file
    jsr SETLFS
    jmp OPEN

; Carry clear if A is a character of an address: - . 0-9 : A-Z a-z
is_address_char:
    cmp #'-'
    beq +
    cmp #'.'
    beq +
    cmp #'0'
    bcc ++
    cmp #':'+1
    bcc +
    cmp #'A'
    bcc ++
    cmp #'Z'+1
    bcc +
    cmp #'a'
    bcc ++
    cmp #'z'+1
    bcc +
++  sec
    rts
+   clc
    rts

read_name:      !text "WIC64 SERVER,S,R"
read_name_end:
write_name:     !text "WIC64 SERVER,S,W"
write_name_end:
scratch_name:   !text "S:WIC64 SERVER"
scratch_name_end:

file_index:     !byte 0
address_loaded: !byte 0
address_changed: !byte 0

ip_request:     !byte "R", WIC64_GET_IP, $00, $00

msg_title:              !scrxor $80, " WiC64 Browser"
                        !fill 40 - (* - msg_title), $a0
                        !byte $ff
msg_enter_address:      !scr "Server address (IP or name:port):", $ff
msg_address_help:       !scr "RETURN = connect    DEL = erase", $ff
msg_this_c64:           !scr "This C64: ", $ff
msg_address_loaded:     !scr "Last used address, loaded from disk", $ff
msg_saving_address:     !scr "Saving the address on disk...", $ff
msg_empty:              !byte $ff
msg_detecting:          !scr "Looking for the WiC64...", $ff
msg_no_device:          !scr "No WiC64 found (or it does not respond)", $ff
msg_legacy_firmware:    !scr "Please update the WiC64 to firmware 2.x", $ff

;------------------------------------------------------------------------------
; Startup only: print a screen code string in any row
;------------------------------------------------------------------------------

; Prints the screen code string at A/Y (terminated by $ff) in row X, padded with spaces
print_row:
    sta print_source+1
    sty print_source+2
    lda row_low,x
    sta print_target+1
    sta print_pad_target+1
    lda row_high,x
    sta print_target+2
    sta print_pad_target+2
    ldx #0
print_source:
-   lda $ffff,x
    cmp #$ff
    beq +
print_target:
    sta $ffff,x
    inx
    cpx #40
    bne -
    rts
+   lda #' '
print_pad_target:
-   sta $ffff,x
    inx
    cpx #40
    bne -
    rts

row_low:
!for row, 0, 24 {
    !byte <(screen + row*40)
}
row_high:
!for row, 0, 24 {
    !byte >(screen + row*40)
}

